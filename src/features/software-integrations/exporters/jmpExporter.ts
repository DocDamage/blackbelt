/**
 * Generate JMP add-in script for reusable Six Sigma tools
 */
export function generateJMPAddIn(): string {
  return `// Six Sigma Tools for JMP
// Save this as an Add-In for reusable Six Sigma analysis tools

// Main menu definition
six_sigma_menu = New Menu("Six Sigma Tools",
  Menu Item("Distribution with Capability",
    <<Script(
      dt = Current Data Table();
      col = Column Dialog(Col = ColList("Select column for analysis:"));
      
      Distribution(
        Continuous Distribution(
          Column(dt, col[1]),
          Quantiles(1),
          Summary Statistics(1),
          Capability Analysis(1)
        )
      );
    )
  ),
  Menu Item("I-MR Control Chart",
    <<Script(
      dt = Current Data Table();
      col = Column Dialog(Col = ColList("Select measurement column:"));
      
      Control Chart Builder(
        Variables(Y(col[1])),
        Chart(Individual Measurement),
        Chart(Moving Range Chart)
      );
    )
  ),
  Menu Item("Process Capability Summary",
    <<Script(
      dt = Current Data Table();
      col = Column Dialog(Col = ColList("Select column(s):"));
      
      Process Capability(
        Process(col),
        Capability Box Plot(1),
        Goal Plot(1),
        Capability Index Plot(1)
      );
    )
  ),
  Menu Item("Capability Sixpack",
    <<Script(
      dt = Current Data Table();
      dlg = Dialog(
        Text Box("Select column for Capability Sixpack:"),
        H List Box(
          Text Box("Column:"),
          col_list = List Box(dt << Get Column Names("Continuous"))
        ),
        Text Box("Specification Limits:"),
        H List Box(Text Box("LSL:"), lsl = Edit Number(0)),
        H List Box(Text Box("USL:"), usl = Edit Number(100)),
        H List Box(Text Box("Target:"), target = Edit Number(50)),
        Button Box("OK", <<Return({col_list, lsl, usl, target})),
        Button Box("Cancel", <<Return({}))
      );
      
      if(N Items(dlg) > 0,
        Process Capability(
          Process(dlg["col_list"][1]),
          Objective Limits(LSL(dlg["lsl"]), USL(dlg["usl"]), Target(dlg["target"])),
          Individual Detail Reports(1),
          Capability Box Plot(1),
          Goal Plot(1),
          Normal Quantile Plot(1)
        )
      );
    )
  ),
  Menu Item("-"),  // Separator
  Menu Item("Gage R&R (Short Form)",
    <<Script(
      Write("\\!NNote: Requires measurement data with Part and Operator columns.\\!N");
      Write("Use: Analyze > Quality and Process > Variability / Attribute Gauge Chart\\!N");
    )
  ),
  Menu Item("Pareto Chart",
    <<Script(
      dt = Current Data Table();
      col = Column Dialog(
        Y = ColList("Select cause column:"),
        Freq = ColList("Select frequency column (optional):")
      );
      
      if(N Items(col["Freq"]) > 0,
        Graph Builder(
          Variables(X(col["Y"][1]), Y(col["Freq"][1])),
          Elements(Bar(X, Y, Summary Statistic("Sum"), Label(Label Values))),
          Ordering(Me(Y, Descending))
        ),
        Graph Builder(
          Variables(X(col["Y"][1])),
          Elements(Histogram(X))
        )
      );
    )
  )
);

// Add menu to main menu bar
Insert Into( Menu( "Analyze" ), -1, six_sigma_menu );

Write("\\!NSix Sigma Tools menu added to Analyze menu.\\!N");
`;
}

