function generateJMPDataFile(dataset: Dataset): string {
  return `# JMP Data File - ${dataset.name}
# Import into JMP using: File > Open
# Or copy data and use: File > New > Data Table

# Column Information:
${dataset.columns.map((col, idx) => `# ${idx + 1}. ${col.name} (${col.type})${col.units ? ` [${col.units}]` : ''}${col.description ? ` - ${col.description}` : ''}`).join('\n')}

# Data (CSV format - save as .csv and open in JMP):
${dataset.columns.map(col => col.name).join(',')}
${dataset.rows.slice(0, 200).map(row => 
  row.map(cell => {
    if (cell === null || cell === undefined) return '';
    if (typeof cell === 'string') return `"${cell}"`;
    return String(cell);
  }).join(',')
).join('\n')}
${dataset.rows.length > 200 ? `
# ... (${dataset.rows.length - 200} more rows)` : ''}
`;
}

