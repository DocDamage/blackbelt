/**
 * JMP Export Generator
 * 
 * Generates JMP scripts and data tables for Six Sigma analysis
 */

import type { Dataset, AnalysisResults, ExportConfig } from '../types';

export interface JMPExport {
  jslScript: string;
  dataFile: string;
  journalTemplate: string;
  filename: string;
}

/**
 * Generate JMP Scripting Language (JSL) for complete analysis
 */
export function generateJMPExport(
  dataset: Dataset,
  results: AnalysisResults,
  config: ExportConfig
): JMPExport {
  const jslScript = generateJSLScript(dataset, results, config);
  const dataFile = generateJMPDataFile(dataset);
  const journalTemplate = generateJMPJournal(dataset, results);
  
  return {
    jslScript,
    dataFile,
    journalTemplate,
    filename: `${dataset.name.replace(/\s+/g, '_')}_JMP.jsl`,
  };
}

function generateJSLScript(
  dataset: Dataset,
  results: AnalysisResults,
  _config: ExportConfig
): string {
  return `// Six Sigma Analysis - JMP Script
// Generated by Six Sigma Training Platform
// Date: ${new Date().toLocaleString()}
// Dataset: ${dataset.name}

// ============================================================
// CLEAR AND SETUP
// ============================================================

Clear Log();
Close All(Data Tables, "No Save");
Close All(Reports, "No Save");

// ============================================================
// CREATE DATA TABLE
// ============================================================

dt = New Table("${dataset.name}",
  Add Rows(${dataset.rows.length}),
${dataset.columns.map((col, idx) => {
  const values = dataset.rows.slice(0, 20).map(r => {
    const val = r[idx];
    if (val === null || val === undefined) return '.';
    if (typeof val === 'string') return `"${val}"`;
    return String(val);
  }).join(', ');
  return `  New Column("${col.name}", Numeric, "Continuous", Format("Best", 10), Set Values([${values}${dataset.rows.length > 20 ? ', ...' : ''}]))`;
}).join(',\n')}
);

// ============================================================
// COLUMN INFORMATION
// ============================================================

${dataset.columns.map(col => `
// Column: ${col.name}
// Type: ${col.type}
${col.description ? `// Description: ${col.description}` : ''}
${col.units ? `// Units: ${col.units}` : ''}
`).join('')}

// ============================================================
// DESCRIPTIVE STATISTICS
// ============================================================

// Distribution analysis
Distribution(
  Continuous Distribution(
    Column(dt, "${dataset.columns[0]?.name || 'Column 1'}"),
    Quantiles(1),
    Summary Statistics(1)
  ),
  By(""),
  SendToReport(
    Dispatch({}, "Distributions", OutlineBox, {Set Title("Descriptive Statistics")})
  )
);

// ============================================================
// VISUALIZATIONS
// ============================================================

// Histogram with capabilities
Graph Builder(
  Variables(X(:${dataset.columns[0]?.name || 'Column 1'})),
  Elements(Histogram(X)),
  SendToReport(
    Dispatch({}, "Graph Builder", OutlineBox, {Set Title("Distribution Histogram")})
  )
);

// Box plot
Graph Builder(
  Variables(Y(:${dataset.columns[0]?.name || 'Column 1'})),
  Elements(Box Plot(Y)),
  SendToReport(
    Dispatch({}, "Graph Builder", OutlineBox, {Set Title("Box Plot")})
  )
);

// Scatter plot matrix (if multiple numeric columns)
Multivariate(
  Y(${dataset.columns.filter(c => c.type === 'numeric').slice(0, 5).map(c => `:${c.name}`).join(', ')}),
  Scatterplot Matrix(
    "Corr Hidden"
  )
);

${results.capability ? generateJSLCapabilityAnalysis(dataset) : ''}

${results.controlChart ? generateJSLControlChart(dataset) : ''}

${results.regression ? generateJSLRegression(dataset) : ''}

${results.anova ? generateJSLANOVA(dataset) : ''}

// ============================================================
// SIX SIGMA REPORT
// ============================================================

// Create summary report
New Window("Six Sigma Summary",
  Outline Box("Analysis Summary",
    Text Box("Dataset: ${dataset.name}"),
    Text Box("Samples: ${dataset.rows.length}"),
    Text Box("Variables: ${dataset.columns.length}"),
    Text Box("Date: ${new Date().toLocaleString()}"),
    ${results.capability ? `
    Text Box(""),
    Text Box("Capability Results:"),
    Text Box("  Cp: ${results.capability.cp.toFixed(3)}"),
    Text Box("  Cpk: ${results.capability.cpk.toFixed(3)}"),
    Text Box("  Sigma Level: ${results.capability.sigmaLevel.toFixed(2)}"),
    ` : ''}
  )
);

// ============================================================
// SAVE OUTPUT
// ============================================================

// Save data table
Save(dt, "$DOCUMENTS/${dataset.name.replace(/\s+/g, '_')}.jmp");

// Save journal (manual step: File > Save > Save Journal)

Write("\\!NSix Sigma Analysis Complete\\!N");
Write("Check Reports window for all analyses.\\!N");
`;
}

function generateJSLCapabilityAnalysis(dataset: Dataset): string {
  return `
// ============================================================
// PROCESS CAPABILITY ANALYSIS
// ============================================================

// Distribution with capability
capability_dist = Distribution(
  Continuous Distribution(
    Column(dt, "${dataset.columns[0]?.name || 'Column 1'}"),
    Quantiles(1),
    Summary Statistics(1),
    Capability Analysis(
      Capability Box Plot(1),
      USL(100),    // Modify as needed
      LSL(0),      // Modify as needed
      Target(50),  // Modify as needed
      Sigma(3),
      Capability Index Pp(1),
      Capability Index Ppk(1),
      Capability Index Cpm(1),
      Z Bench(1),
      ZLSL(1),
      ZUSL(1),
      PCI(1),
      Cpk(1),
      Cp(1)
    ),
    Fit Distribution(Normal)
  ),
  By(""),
  SendToReport(
    Dispatch({}, "Distributions", OutlineBox, {Set Title("Process Capability Analysis")})
  )
);

// Capability Sixpack
Process Capability(
  Process(${dataset.columns[0]?.name || 'Column 1'}),
  Objective Limits(LSL(0), USL(100), Target(50)),
  Individual Detail Reports(1),
  Capability Box Plot(1),
  Goal Plot(1),
  Capability Index Plot(1),
  Normal Quantile Plot(1)
);

// Create capability summary table
cap_summary = dt << Summary(
  Mean(${dataset.columns[0]?.name || 'Column 1'}),
  Std Dev(${dataset.columns[0]?.name || 'Column 1'}),
  Min(${dataset.columns[0]?.name || 'Column 1'}),
  Max(${dataset.columns[0]?.name || 'Column 1'})
);
`;
}

